import { readFile, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const marker = "/*__ZHANSHI_CORE__*/";
const [template, core] = await Promise.all([
  readFile(new URL("lib/client.template.js", root), "utf8"),
  readFile(new URL("lib/core.js", root), "utf8"),
]);
if (!template.includes(marker)) throw new Error("client.template.js is missing the shared-core marker");
const embedded = core.replace(/^export (?=(?:const|function) )/gm, "").trim();
const generated = "// Generated by scripts/build-client.mjs from lib/client.template.js and lib/core.js.\n" + template.replace(marker, () => embedded);
const target = new URL("lib/client.js", root);

if (process.argv.includes("--check")) {
  const current = await readFile(target, "utf8").catch(() => "");
  if (current !== generated) {
    console.error("lib/client.js is stale; run npm run build");
    process.exitCode = 1;
  }
} else {
  await writeFile(target, generated);
}
